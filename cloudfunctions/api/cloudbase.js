/* ============================================================
   cloudbase.js —— 数据库「连接层」（Day 19 重构时新增）
   ============================================================
   ⭐ 这一层**只管一件事：连上数据库**，然后把连好的 `db` 对象交出去。

   ⚠️ 为什么要单独一个文件（而不是每个 repository 自己 init 一次）：
       `cloudbase.init()` 是"建立连接"的动作 —— 重复调用既浪费，也会让
       "环境 ID 写在哪"变成一个谜。⭐ 现在全项目只有这里知道环境 ID。

   ⭐ 谁用它：`repositories/` 下的每个文件。各层职责见 index.js 顶部的说明。
   ============================================================ */

const cloudbase = require('@cloudbase/node-sdk');

/* ⚠️ 为什么显式传 env 而不让 SDK 自己猜：
      官方示例在"普通云函数"里可以 init({})（环境变量自动注入），
      但我们是 **HTTP 云函数**，形态不同，**显式传更稳**。
   ⚠️ 环境 ID 不是密钥（它是半公开的，前端代码里本来就会出现）。 */
const ENV_ID = 'tripmemo-d3gd23bd14a396d1d';

const app = cloudbase.init({ env: ENV_ID });

/* ⭐ 只导出"连好的数据库对象" ——
   ⚠️ 上层拿到的就是它，看不到 init 是怎么做的。 */
const db = app.database();

module.exports = {
  db: db,
  ENV_ID: ENV_ID,
};
